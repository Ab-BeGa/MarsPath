export type RegionField = 'name' | 'type' | 'summary' | 'science' | 'note'
const regionIndex: Record<RegionField, number> = { name:0, type:1, summary:2, science:3, note:4 }

export function regionText(region: DetailedRegion, locale: Locale, field: RegionField): string {
  if (locale === 'ru') {
    return field === 'name' ? region.name_ru : field === 'type' ? region.feature_type_ru :
      field === 'summary' ? region.summary_ru : field === 'science' ? region.science_ru : region.data_note_ru
  }
  const translated = regionCopy[region.id as keyof typeof regionCopy]?.[locale]?.[regionIndex[field]]
  return translated ?? (field === 'name' ? region.name : '—')
}
