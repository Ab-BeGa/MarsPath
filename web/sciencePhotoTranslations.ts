export type PhotoField = 'title' | 'caption' | 'note'
const photoIndex: Record<PhotoField, number> = {title:0, caption:1, note:2}
export function photoText(photo: JezeroPhoto, locale: Locale, field: PhotoField): string {
  if (locale === 'en') return field === 'title' ? photo.title : field === 'caption' ? photo.caption : photo.coordinates?.note ?? ''
  const value = photoCopy[photo.id as keyof typeof photoCopy]?.[locale]?.[photoIndex[field]]
  return value ?? (field === 'title' ? photo.title : field === 'caption' ? photo.caption : photo.coordinates?.note ?? '')
}
